# Rebuild the embedded shader words after editing the GLSL sources.
param([string]$Sdk = $env:VULKAN_SDK)
$ErrorActionPreference = 'Stop'
$compiler = Join-Path $Sdk 'Bin/glslc.exe'
$output = @('// Generated by Shaders/compile.ps1 from Triangle.vert and Triangle.frag.', 'TriangleShaders', '#{')
foreach ($stage in 'vert', 'frag') {
    $tempFile = [IO.Path]::GetTempFileName()
    try {
        & $compiler -O (Join-Path $PSScriptRoot "Triangle.$stage") -o $tempFile
        if ($LASTEXITCODE) { throw "Failed to compile Triangle.$stage" }
        $bytes = [IO.File]::ReadAllBytes($tempFile)
        $words = for ($i = 0; $i -lt $bytes.Length; $i += 4) { [BitConverter]::ToUInt32($bytes, $i) }
        $method = if ($stage -eq 'vert') { 'Vertex' } else { 'Fragment' }
        $output += "    long $method(long device)"
        $output += '    {'
        $output += "        uint [$($words.Count)] code = {" + ($words -join ', ') + '}'
        $output += '        VkShaderModuleCreateInfo info'
        $output += "        info.codeSize = $($bytes.Length)"
        $output += '        info.pCode = &code[0]'
        $output += '        long shader = 0'
        $output += '        if Vk.CreateShaderModule(device, &info, null, &shader) != 0 { return 0 }'
        $output += '        return shader'
        $output += '    }'
    } finally { Remove-Item -LiteralPath $tempFile }
}
$output += '}'
$output | Set-Content (Join-Path $PSScriptRoot '../Source/Platform/Windows/Vulkan/TriangleShaders.dk')
