# Rebuild the embedded shader words after editing the GLSL sources.
param([string]$Sdk = $env:VULKAN_SDK)
$ErrorActionPreference = 'Stop'
$compiler = Join-Path $Sdk 'Bin/glslc.exe'

# Returns the Duck lines of one method that creates a shader module.
function Compile([string]$source, [string]$method) {
    $tempFile = [IO.Path]::GetTempFileName()
    try {
        & $compiler -O $source -o $tempFile
        if ($LASTEXITCODE) { throw "Failed to compile $source" }
        $bytes = [IO.File]::ReadAllBytes($tempFile)
        $words = for ($i = 0; $i -lt $bytes.Length; $i += 4) { [BitConverter]::ToUInt32($bytes, $i) }
        @(
            "    long $method(long device)"
            '    {'
            "        uint [$($words.Count)] code = {" + ($words -join ', ') + '}'
            '        VkShaderModuleCreateInfo info'
            "        info.codeSize = $($bytes.Length)"
            '        info.pCode = &code[0]'
            '        long shader = 0'
            '        if Vk.CreateShaderModule(device, &info, null, &shader) != 0 { return 0 }'
            '        return shader'
            '    }'
        )
    } finally { Remove-Item -LiteralPath $tempFile }
}

foreach ($shader in 'Mesh', 'Voxel', 'Ui') {
    $output = @("// Generated by Shaders/compile.ps1 from $shader GLSL.", "${shader}Shaders", '#{')
    foreach ($stage in $(if ($shader -eq 'Mesh') { 'vert', 'frag' } else { 'comp' })) {
        $method = if ($stage -eq 'vert') { 'Vertex' } elseif ($stage -eq 'frag') { 'Fragment' } else { 'Compute' }
        $output += Compile (Join-Path $PSScriptRoot "$shader.$stage") $method
    }
    $output += '}'
    $output | Set-Content (Join-Path $PSScriptRoot "../Source/Platform/Windows/Vulkan/${shader}Shaders.dk")
}

# The effect passes share EffectCommon.glsl and live in one generated file.
$output = @('// Generated by Shaders/compile.ps1 from the Effect*.comp GLSL.', 'EffectShaders', '#{')
foreach ($pass in 'Bake', 'Sim', 'Clear', 'Stamp', 'Bricks') {
    $output += Compile (Join-Path $PSScriptRoot "Effect$pass.comp") $pass
}
$output += '}'
$output | Set-Content (Join-Path $PSScriptRoot '../Source/Platform/Windows/Vulkan/EffectShaders.dk')
