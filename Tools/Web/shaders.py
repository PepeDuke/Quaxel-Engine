"""Regenerate browser compute kernels from the engine GLSL with glslc and naga."""
import argparse
from pathlib import Path
import re
import subprocess
import tempfile

root = Path(__file__).resolve().parents[2]
shaders = root / "Shaders"
out = root / "Source/Platform/Web/Shaders"
parser = argparse.ArgumentParser()
parser.add_argument("--naga", default="naga")
args = parser.parse_args()

def expand(path):
    return re.sub(r'^#include "([^"]+)"', lambda m: expand(shaders / m[1]),
                  path.read_text(), flags=re.MULTILINE)

# WebGPU binds pass constants as uniforms and addresses one slot per storage buffer.
sources = {}
for name in ("Bake", "Sim", "Clear", "Stamp", "Bricks"):
    source = expand(shaders / f"Effect{name}.comp")
    source = source.replace("layout(push_constant)", "layout(set=0,binding=1,std140)")
    source = source.replace("set=1,binding=0", "set=0,binding=2")
    sources["Effect" + name] = ("comp", source)
voxel = (out.parent / "voxel.frag").read_text()
for name, defines in [("Voxel", ""), ("VoxelShadow", "#define QUAXEL_DEPTH_ONLY\n")]:
    sources[name] = ("frag", voxel.replace("#version 450", "#version 450\n" + defines))
for name, (stage, source) in sources.items():
    with tempfile.TemporaryDirectory(dir=Path.cwd()) as tmp:
        directory = Path(tmp).relative_to(Path.cwd())
        glsl = directory / ("kernel." + stage)
        spirv = directory / "kernel.spv"
        wgsl = directory / "kernel.wgsl"
        glsl.write_text(source)
        subprocess.run(["glslc", str(glsl), "-o", str(spirv)], check=True)
        subprocess.run([args.naga, str(spirv), str(wgsl)], check=True)
        code = wgsl.read_text()
        # GLSL samplerless textures carry no depth type. Both shadow views are depth-only.
        if name == "Voxel":
            code = code.replace("texture_2d<f32>", "texture_depth_2d")
            code = re.sub(r"(textureLoad\((?:shadowMap|pointMap),.*\));", r"vec4<f32>(\1);", code)
        (out / f"{name}.wgsl").write_text(
            "// Generated by Tools/Web/shaders.py.\n" +
            "\n".join(line.rstrip() for line in code.splitlines()) + "\n")
